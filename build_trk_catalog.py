#!/usr/bin/env python3
"""Build the pinned Play Booster inventory. See README.md#star-trek-booster-rules."""
import argparse
import json
from pathlib import Path
from fetch_cards import fetch

SOURCE = 'https://magic.wizards.com/en/news/feature/collecting-star-trek'
DUALS = {'Andoria', 'Bajor', 'Cardassia Prime', 'Earth, Sector 001', 'Ferenginar',
         'Orion', "Qo'noS", 'Risa', 'Romulus', 'Vulcan'}
RANGES = {'away': (307, 311), 'holodeck': (312, 316), 'basic': (317, 326),
          'borderless': (332, 337), 'scene': (338, 362), 'lcars': (363, 391),
          'shock': (392, 401), 'classic': (402, 425), 'klingon': (426, 435)}
EXPECTED = {'main.common':81, 'main.uncommon':110, 'main.rare':80, 'main.mythic':25,
            'dual':10, 'away':5, 'holodeck':5, 'basic':10, 'sds':30,
            'borderless.rare':5, 'borderless.mythic':1,
            'scene.uncommon':10, 'scene.rare':8, 'scene.mythic':7,
            'lcars.uncommon':7, 'lcars.rare':14, 'lcars.mythic':8,
            'shock.rare':10, 'classic.uncommon':5, 'classic.rare':13, 'classic.mythic':6,
            'klingon.common':1, 'klingon.uncommon':6, 'klingon.rare':3}


def download(code):
    url = f'https://api.scryfall.com/cards/search?q=set%3A{code}&unique=prints&order=set'
    cards = []
    while url:
        page = json.loads(fetch(url))
        cards.extend(page['data'])
        url = page.get('next_page') if page.get('has_more') else None
    return cards


def build(trk, sds):
    cards, pools = {}, {}
    for c in sorted(trk + sds, key=lambda c: (c['set'], int(c['collector_number']) if c['collector_number'].isdigit() else 99999)):
        n = c['collector_number']
        if c['lang'] != 'en' or not n.isdigit():
            continue
        n = int(n)
        slot = None
        if c['set'] == 'sds' and 1 <= n <= 30:
            slot = 'sds'
        elif c['set'] == 'trk':
            if 1 <= n <= 306:
                slot = 'dual' if c['name'] in DUALS else 'main.' + c['rarity']
            else:
                for category, (lo, hi) in RANGES.items():
                    if lo <= n <= hi:
                        slot = category if category in ('away', 'holodeck', 'basic') else category + '.' + c['rarity']
                        break
        if not slot:
            continue
        key = c['set'].upper() + ':' + c['name']
        pools.setdefault(slot, []).append(key)
        if key in cards:
            continue
        face = c.get('card_faces', [c])[0]
        imgs = c.get('image_uris') or face.get('image_uris')
        if not imgs:
            raise ValueError(f'Missing image: {key}')
        cards[key] = dict(key=key, name=c['name'], set=c['set'].upper(), rarity=c['rarity'],
                          aliases=[c['flavor_name']] if c.get('flavor_name') else [],
                          cost=c.get('mana_cost', face.get('mana_cost', '')),
                          colors=c.get('colors', face.get('colors', [])), mana_value=c['cmc'],
                          is_land='Land' in c['type_line'], is_basic='Basic' in c['type_line'],
                          produced_mana=c.get('produced_mana', []), image=imgs['normal'])
    actual = {k: len(v) for k, v in pools.items()}
    if actual != EXPECTED:
        raise ValueError(f'Unexpected inventory: {actual}')
    if len(cards) != 341:
        raise ValueError(f'Expected 341 gameplay identities, got {len(cards)}')
    # The ten default basic printings intentionally collapse to five identities.
    for k, pool in pools.items():
        if k != 'basic' and len(pool) != len(set(pool)):
            raise ValueError(f'Duplicate identity in {k}')
    return dict(source=SOURCE, scryfall_sets=['TRK', 'SDS'], cards=list(cards.values()), pools=pools)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, help='Directory containing trk.json and sds.json printings')
    args = parser.parse_args()
    source = lambda code: json.loads((args.source_dir / f'{code}.json').read_text()) if args.source_dir else download(code)
    catalog = build(source('trk'), source('sds'))
    Path('trk_catalog.js').write_text('/* Generated by build_trk_catalog.py; explicit Play Booster ranges, not Scryfall booster flags. */\n(function(root) {\n  const catalog = ' + json.dumps(catalog, ensure_ascii=False, indent=1) + ';\n  if (typeof module !== "undefined" && module.exports) module.exports = catalog;\n  else root.TRK_CATALOG = catalog;\n})(globalThis);\n')
    print(f"Wrote {len(catalog['cards'])} identities across {len(catalog['pools'])} printing pools.")
